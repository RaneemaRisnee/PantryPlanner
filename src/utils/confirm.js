import { Alert, Platform } from 'react-native';

// Alert buttons do nothing in react-native-web, so the web build uses browser dialogs.
export function confirmAction(title, message, confirmLabel, onConfirm) {
  if (Platform.OS === 'web') {
    if (window.confirm(`${title}\n\n${message}`)) onConfirm();
    return;
  }
  Alert.alert(title, message, [
    { text: 'Cancel', style: 'cancel' },
    { text: confirmLabel, style: 'destructive', onPress: onConfirm },
  ]);
}

export function confirmDelete(title, message, onConfirm) {
  confirmAction(title, message, 'Delete', onConfirm);
}

export function notify(title, message) {
  if (Platform.OS === 'web') {
    window.alert(`${title}\n\n${message}`);
    return;
  }
  Alert.alert(title, message);
}
